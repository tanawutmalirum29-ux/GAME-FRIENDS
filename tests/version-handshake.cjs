'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const source=fs.readFileSync('src/app/core/version-protocol.js','utf8');
const ctx={window:{GAME_CORE_VERSION:'a'.repeat(20)}};
vm.runInNewContext(source,ctx);
const hello=vm.runInNewContext('gfVersionHello()',ctx);
assert.equal(hello.coreHash,'a'.repeat(20));
assert.equal(hello.protocolVersion,1);
const accepts=p=>vm.runInNewContext('gfVersionsCompatible(packet)',Object.assign(ctx,{packet:p}));
assert.equal(accepts(hello),true);
assert.equal(accepts({...hello,protocolVersion:2}),false);
assert.equal(accepts({...hello,coreHash:'b'.repeat(20)}),false);
assert.equal(accepts({}),false,'Production rejects unversioned controllers safely');
ctx.window.GAME_CORE_VERSION=null;
assert.equal(accepts({}),true,'Source/fixture builds without deployment hash remain compatible');
const host=fs.readFileSync('src/app/host/room.js','utf8');
const joy=fs.readFileSync('src/app/controller/connection.js','utf8');
assert.match(host,/if\(!gfVersionsCompatible\(msg\)\)/);
assert.match(joy,/if\(!gfVersionsCompatible\(data\)\)/);
assert.match(host,/pluginHash:round\?\.pluginHash/);
console.log('TRANSPORT VERSION HANDSHAKE PASS: authenticated join, protocol, immutable Core and safe refusal');
