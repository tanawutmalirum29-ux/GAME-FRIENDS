'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const src=fs.readFileSync('src/app/board/integration.js','utf8');
const ctrl=fs.readFileSync('src/app/controller/connection.js','utf8');
const ctx=vm.createContext({window:{},controllerBoard:null,console});
vm.runInContext(src,ctx);
const valid=packet=>vm.runInContext('validBoardItemMeta(packet)',Object.assign(ctx,{packet}));
const ids=['potion','ufo','rocket','bomber','car','shield','future-item'];
const names=Object.fromEntries(ids.map(id=>[id,id==='future-item'?'Future Item':id]));
const packet={t:'board-item-meta',sessionId:'board-123',ids,names};
assert.equal(valid(packet),true,'Unknown item is accepted as host-provided metadata');
assert.equal(valid({...packet,ids:[...ids,'potion']}),false,'duplicates rejected');
assert.equal(valid({...packet,ids:['potion','ufo','rocket','bomber','car']}),false);
assert.equal(valid({...packet,names:{...names,'future-item':'X'.repeat(100)}}),false);
assert.equal(valid({...packet,ids:[...ids,'../escape']}),false);
assert.equal(valid({...packet,ids:Array(61).fill('fake')}),false);
ctx.packet=packet;vm.runInContext('receiveBoardItemMeta(packet)',ctx);
const actual=vm.runInContext('phoneBoardItemMeta',ctx);
assert.equal(actual.sessionId,'board-123');
assert.equal(actual.ids.at(-1),'future-item');
assert.equal(actual.names['future-item'],'Future Item');
assert.match(src,/boardItemMetaSession!==boardSession\.id/);
assert.match(src,/send\(conn,\{t:'board-item-meta'/);
assert.match(src,/sessionId:boardSession\.id,mapVersion/);
assert.match(src,/phoneBoardItemMeta\?\.sessionId===info\.sessionId/);
assert.match(ctrl,/data\.t==='board-item-meta'/);
assert.match(ctrl,/phoneBoardItemMeta=null/);
console.log('BOARD CONTROLLER ITEM META PASS: host authoritative slots, one packet per session, unknown item and validation');
