'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const source=fs.readFileSync('src/app/core/connection-compat.js','utf8');
const ctx={window:{GAME_CORE_HASH:'a'.repeat(20)}};
vm.runInNewContext(source,ctx);
const hello=vm.runInNewContext('gfConnectionHello()',ctx);
assert.equal(hello.coreHash,'a'.repeat(20));
assert.equal(Object.hasOwn(hello,'protocolVersion'),false,'Core hello must not advertise numeric releases');
const accepts=p=>vm.runInNewContext('gfConnectionCompatible(packet)',Object.assign(ctx,{packet:p}));
assert.equal(accepts(hello),true);
assert.equal(accepts({...hello,protocolVersion:1}),false,'legacy numbered protocol rejected');
assert.equal(accepts({...hello,protocolVersion:2}),false);
assert.equal(accepts({...hello,coreHash:'b'.repeat(20)}),false);
assert.equal(accepts({}),false,'Production rejects packets lacking a matching Core fingerprint');
ctx.window.GAME_CORE_HASH=null;
assert.equal(accepts({}),true,'Source/fixture builds without deployment hash remain compatible');
const host=fs.readFileSync('src/app/host/room.js','utf8');
const joy=fs.readFileSync('src/app/controller/connection.js','utf8');
assert.match(host,/if\(!gfConnectionCompatible\(msg\)\)/);
assert.match(joy,/if\(!gfConnectionCompatible\(data\)\)/);
assert.match(host,/pluginHash:round\?\.pluginHash/);
console.log('TRANSPORT CORE HANDSHAKE PASS: authenticated join, immutable fingerprint and safe refusal');
