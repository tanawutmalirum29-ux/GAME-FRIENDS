'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const ctx=vm.createContext({Date,Math,window:{}});
vm.runInContext(fs.readFileSync('src/app/core/connection-guard.js','utf8'),ctx);
let clock=1000;
ctx.clock=()=>clock;
const create=()=>vm.runInContext('createControllerIngressGuard(clock)',ctx);
const input={t:'input',keys:{axisX:0.9,axisY:-0.4,action:true,alt:false,cancel:false},actionId:1};
const ingress=create();
assert.equal(ingress.accept({t:'join',name:'Player',clientToken:'stable-1234567890'}),true);
for(let i=0;i<180;i++)assert.equal(ingress.accept(input),true,'180 burst legal inputs');
assert.equal(ingress.accept({t:'board-camera-gesture',kind:'pan',dx:4,dy:3}),true);
let accepted=0;
for(let i=0;i<2000;i++)if(ingress.accept(input))accepted++;
assert.ok(accepted<=80,'burst bounded by remaining token budget');
clock+=1000;
for(let i=0;i<170;i++)assert.equal(ingress.accept(input),true,'180/s refill supports joystick');
assert.equal(ingress.accept({t:'input',keys:{axisX:2}}),false);
assert.equal(ingress.accept({t:'input',keys:{axisX:NaN}}),false);
assert.equal(ingress.accept({t:'input',keys:{action:'true'}}),false);
assert.equal(ingress.accept({t:'input',keys:{unexpected:true}}),false);
assert.equal(ingress.accept({t:'input',keys:[]}),false);
assert.equal(ingress.accept({t:'join',name:'X'.repeat(6000)}),false);
assert.equal(ingress.accept({t:'unknown'}),false);
assert.equal(ingress.accept('invalid'),false);
assert.equal(ingress.accept(null),false);
assert.equal(ingress.accept({t:'input',keys:{},nested:{huge:'x'.repeat(8000)}}),false);
const cyclic={t:'input',keys:{}};cyclic.self=cyclic;
assert.equal(ingress.accept(cyclic),false);
assert.equal(ingress.accept({t:'board-camera-zoom',direction:8}),false);
assert.equal(ingress.accept({t:'result-vote',choice:'next'}),true);
ingress.dispose();assert.equal(ingress.accept(input),false,'closed data connection is inert');
const independent=create();assert.equal(independent.accept(input),true,'per-connection counters isolated');
console.log('CONTROLLER INGRESS PASS: valid joystick, 180Hz refill, burst, payload/type/structure guards, cleanup');
